// UI checks use a fresh local browser context; no real human review is signed.
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || process.argv[2] || 'playwright');
const fs = require('node:fs/promises');
const path = require('node:path');
const assert = require('node:assert/strict');
(async()=>{
  const output=path.resolve('artifacts/parser-benchmark/ui-check');
  await fs.mkdir(output,{recursive:true});
  const browser=await chromium.launch({channel:'msedge',headless:true});
  const context=await browser.newContext({viewport:{width:1440,height:1080},reducedMotion:'reduce'});
  const page=await context.newPage();const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:18090',{waitUntil:'networkidle'});
  assert.equal(await page.getByRole('heading',{name:'解析质量，有据可查。'}).count(),1);
  assert.equal(await page.locator('.card').count(),8);
  assert.equal(await page.locator('.sample').count(),100);
  await page.getByLabel('筛选核验范围').selectOption('review');
  assert.equal(await page.locator('.sample').count(),20);
  await page.getByLabel('选择引擎').selectOption('mineru_cloud');
  await page.locator('#source-image').evaluate(img => img.decode());
  assert(await page.locator('#source-image').evaluate(img=>img.naturalWidth>500));
  assert.equal(await page.getByLabel('人工核验结论').inputValue(),'pending');
  await page.screenshot({path:path.join(output,'desktop.png'),fullPage:true});
  await page.getByLabel('人工核验结论').selectOption('confirmed');
  await page.getByRole('button',{name:'保存本页核验'}).click();
  assert.equal(await page.getByRole('status').innerText(),'请填写实际审核人');
  await page.getByLabel('实际审核人',{exact:true}).fill('自动化交互测试（非人工核验）');
  await page.getByLabel('人工核验结论').selectOption('pending');
  await page.getByRole('button',{name:'保存本页核验'}).click();
  const [download]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'导出人工核验记录'}).click()]);
  const raw=await fs.readFile(await download.path(),'utf8');
  assert(JSON.parse(raw).items.every(x=>x.status==='pending'&&x.reviewed_at===null));
  await page.getByLabel('人工核验备注').fill('Result identity test fixture');
  await page.getByRole('button',{name:'保存本页核验'}).click();
  await page.evaluate(()=>{D.samples.find(s=>s.id===selected).results[document.getElementById('engine').value].review_fingerprint='changed-for-ui-test';draw()});
  assert.equal(await page.getByLabel('人工核验备注').inputValue(),'');
  const [changedDownload]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'导出人工核验记录'}).click()]);
  const changed=JSON.parse(await fs.readFile(await changedDownload.path(),'utf8'));
  assert.equal(changed.items.length,0);
  assert.equal(changed.review_history.length,1);
  await page.setViewportSize({width:390,height:844});
  await page.getByLabel('实际审核人',{exact:true}).fill('');
  await page.screenshot({path:path.join(output,'mobile.png'),fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
  assert.deepEqual(errors,[]);
  await fs.writeFile(path.join(output,'checks.json'),JSON.stringify({passed:true,checks:['eight_engine_cards','100_page_evidence','source_page_pixels_loaded','20_page_review_queue','reviewer_required','pending_export_is_not_human_approval','changed_result_invalidates_review_and_keeps_history','mobile_no_overflow','no_browser_errors']},null,2));
  await browser.close();console.log('9 browser checks passed');
})().catch(e=>{console.error(e);process.exit(1)});
